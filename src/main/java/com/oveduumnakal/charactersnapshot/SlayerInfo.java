	private SlayerInfo()
	{
	}

	/**
	 * @param masterId the value of the slayer master varbit
	 * @return the master's name, or null when the id is 0 or unknown
	 */
	static String masterName(int masterId)
	{
		if (masterId <= 0 || masterId >= MASTER_NAMES.length)
			return null;

		return MASTER_NAMES[masterId];
	}

	/**
	 * @return an unmodifiable view of the per-master block varbits
	 */
	static Map<String, int[]> blockVarbits()
	{
		return Collections.unmodifiableMap(BLOCK_VARBITS);
	}
